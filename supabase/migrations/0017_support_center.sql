-- IMDS Customer Success and Support Center.
-- Staff writes are exposed only through guarded RPC functions.

create type public.support_ticket_priority as enum ('low', 'normal', 'high', 'urgent');
create type public.support_ticket_status as enum ('new', 'open', 'pending_customer', 'pending_internal', 'resolved', 'closed');
create type public.support_ticket_channel as enum ('portal', 'email', 'whatsapp', 'phone', 'internal');
create type public.support_author_type as enum ('customer', 'staff', 'system');

create table public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  organization_id uuid not null references public.organizations(id) on delete restrict,
  product_id uuid references public.products(id) on delete set null,
  subject text not null,
  description text,
  category text not null default 'Другое',
  priority public.support_ticket_priority not null default 'normal',
  status public.support_ticket_status not null default 'new',
  channel public.support_ticket_channel not null default 'portal',
  requester_name text,
  requester_email text,
  assignee_id uuid references public.platform_users(id) on delete set null,
  first_response_due_at timestamptz,
  resolution_due_at timestamptz,
  first_responded_at timestamptz,
  resolved_at timestamptz,
  last_message_at timestamptz not null default now(),
  created_by uuid references public.platform_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (char_length(btrim(subject)) between 3 and 240),
  check (requester_email is null or requester_email = '' or requester_email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  check (resolved_at is null or resolved_at >= created_at),
  check (first_responded_at is null or first_responded_at >= created_at)
);

create table public.support_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  author_id uuid references public.platform_users(id) on delete set null,
  author_name text,
  author_type public.support_author_type not null,
  body text not null,
  is_internal boolean not null default false,
  created_at timestamptz not null default now(),
  check (char_length(btrim(body)) between 1 and 20000),
  check (not is_internal or author_type <> 'customer')
);

create table public.support_events (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  event_type text not null,
  actor_id uuid references public.platform_users(id) on delete set null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  check (event_type ~ '^[a-z0-9]+([._-][a-z0-9]+)*$')
);

create index support_tickets_queue_idx on public.support_tickets(status, priority, last_message_at desc);
create index support_tickets_organization_idx on public.support_tickets(organization_id, created_at desc);
create index support_tickets_assignee_idx on public.support_tickets(assignee_id, status) where status not in ('resolved', 'closed');
create index support_tickets_sla_idx on public.support_tickets(first_response_due_at, resolution_due_at) where status not in ('resolved', 'closed');
create index support_messages_ticket_idx on public.support_messages(ticket_id, created_at);
create index support_events_ticket_idx on public.support_events(ticket_id, created_at desc);

